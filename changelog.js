function renderWhatsNew() {
  const tag = { 'ใหม่': 'ai', 'แก้ไข': '', 'ย้าย': '' };
  $('news-body').innerHTML = CHANGELOG.map((v, i) => `
    <section class="news-ver">
      <div class="row" style="gap:10px;align-items:baseline;flex-wrap:wrap"><h4>เวอร์ชัน ${esc(v.version)}</h4>${i === 0 ? '<span class="tag ai">ล่าสุด</span>' : ''}<span class="hint">${esc(v.date)}</span></div>
      <p class="news-title">${esc(v.title)}</p>
      ${v.sections.map((s) => `<div class="news-sec"><b>${esc(s.h)}</b>${s.items ? `<ul>${s.items.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>` : ''}
        ${s.files ? `<div class="tbl-wrap"><table class="tbl"><thead><tr><th>ไฟล์</th><th>สถานะ</th><th>รายละเอียด</th></tr></thead><tbody>${s.files.map(([f, st, d]) => `<tr><td><code>${esc(f)}</code></td><td><span class="tag ${tag[st] || ''}">${esc(st)}</span></td><td>${esc(d)}</td></tr>`).join('')}</tbody></table></div>` : ''}</div>`).join('')}
    </section>`).join('');
}
function showWhatsNew() { renderWhatsNew(); openDlg('dlg-news'); LS.set('seenVersion', APP_VERSION); }
function initWhatsNew() {
  $('app-version').textContent = APP_VERSION;
  $('dlg-news').addEventListener('mousedown', (e) => { if (e.target.id === 'dlg-news') closeDlg('dlg-news'); });
  if (LS.get('seenVersion', null) !== APP_VERSION) setTimeout(showWhatsNew, 500);
}
